"""Project scaffolding + script running + reporting (``new`` / ``run`` / ``report``).

Preserves the behaviour of the original argparse CLI exactly.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import click

_TASKS_PY = '''"""Generated by `visus-desktop new` -- write your automation inside the `with`."""

from visus.desktop import rpa


def run() -> None:
    # Every action is a step of ./visus-runs/<name>-<timestamp>/report.html
    # (written even when a step fails; a failed step stops the run, exit code 1).
    # Open the app first with: rpa(..., app="notepad", window="Notepad")
    with rpa(__NAME__, open_report=True) as bot:
        bot.type_text("Hello from visus-desktop")


if __name__ == "__main__":
    run()
'''

_README_MD = """# {name}

Generated by `visus-desktop new`. Write your automation inside the `with rpa(...)`
block of `tasks.py` and run it with:

```bash
visus-desktop run tasks.py
```

Each run writes `visus-runs/<name>-<timestamp>/run.zip` + `report.html` (every
step with its duration, OK/FAILED + reason, a screenshot and its logs) and opens
the report. See the cookbook at
https://github.com/botvisus/visus-framework-desktop for worked examples.
"""

_GITIGNORE = """\
visus-runs/
visus-artifacts/
__pycache__/
.venv/
*.pyc
.DS_Store
"""


@click.command(help="Scaffold a new visus-desktop bot project.")
@click.argument("path")
@click.option("--force", is_flag=True, help="Overwrite an existing directory.")
def new(path, force):
    target = Path(path)
    if target.exists() and not force:
        click.echo(
            f"error: {target} already exists. Re-run with --force to overwrite.",
            err=True,
        )
        click.get_current_context().exit(1)
    target.mkdir(parents=True, exist_ok=True)
    script = _TASKS_PY.replace("__NAME__", repr(target.resolve().name or "run"))
    (target / "tasks.py").write_text(script, encoding="utf-8")
    (target / "README.md").write_text(
        _README_MD.format(name=target.name), encoding="utf-8"
    )
    (target / ".gitignore").write_text(_GITIGNORE, encoding="utf-8")
    click.echo(f"Scaffolded a new visus-desktop project at {target}.")


@click.command(
    help=(
        "Run a Python script via the active interpreter and propagate its exit "
        "code. A script built on rpa() writes its report to "
        "./visus-runs/<name>-<timestamp>/ and exits 1 when a step fails."
    )
)
@click.argument("script")
def run(script):
    rc = subprocess.call([sys.executable, script])
    click.get_current_context().exit(rc)


@click.command(help="Render a session zip (run.zip) to a single-file HTML report.")
@click.argument("zip_path")
@click.option("--html", required=True, help="Output HTML path.")
@click.option("--title", default=None, help="Report headline (default: the run's name).")
def report(zip_path, html, title):
    from visus.desktop.core.session import Session

    written = Session.write_report(zip_path, html, title=title)
    click.echo(f"Wrote {written}")
