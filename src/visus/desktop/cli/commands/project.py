"""Project scaffolding + script running + reporting (``new`` / ``run`` / ``report``).

Preserves the behaviour of the original argparse CLI exactly.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import click

_TASKS_PY = '''"""Generated by `visus new` -- edit this list to drive your bot."""

from visus.desktop import VisusBot

bot = VisusBot()

tasks = [
    {"type": "type_text", "text": "Hello from visus-desktop"},
]

if __name__ == "__main__":
    results = bot.execute_tasks(tasks)
    for r in results:
        print(f"{r.task_index + 1}. {r.task_name} -> {r.success}")
'''

_README_MD = """# {name}

Generated by `visus new`. Edit `tasks.py` to define your automation
and run it with:

```bash
visus run tasks.py
```

See the visus-desktop cookbook at
https://github.com/matheuszwilk/visus-desktop for worked examples.
"""

_GITIGNORE = """\
visus-artifacts/
__pycache__/
.venv/
*.pyc
.DS_Store
"""


@click.command(help="Scaffold a new visus-desktop bot project.")
@click.argument("path")
@click.option("--force", is_flag=True, help="Overwrite an existing directory.")
def new(path, force):
    target = Path(path)
    if target.exists() and not force:
        click.echo(
            f"error: {target} already exists. Re-run with --force to overwrite.",
            err=True,
        )
        click.get_current_context().exit(1)
    target.mkdir(parents=True, exist_ok=True)
    (target / "tasks.py").write_text(_TASKS_PY, encoding="utf-8")
    (target / "README.md").write_text(
        _README_MD.format(name=target.name), encoding="utf-8"
    )
    (target / ".gitignore").write_text(_GITIGNORE, encoding="utf-8")
    click.echo(f"Scaffolded a new visus-desktop project at {target}.")


@click.command(help="Run a Python script via the active interpreter.")
@click.argument("script")
def run(script):
    rc = subprocess.call([sys.executable, script])
    click.get_current_context().exit(rc)


@click.command(help="Render a session zip to HTML.")
@click.argument("zip_path")
@click.option("--html", required=True, help="Output HTML path.")
def report(zip_path, html):
    from visus.desktop.core.session import Session

    Session.write_report(zip_path, html)
    click.echo(f"Wrote {html}")
