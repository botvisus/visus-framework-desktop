"""``visus`` CLI -- Phase 5 / D2.

Subcommands:
  * ``visus new <path>``               -- scaffold a new bot project.
  * ``visus run <script>``             -- execute a Python script.
  * ``visus report <zip> --html FILE`` -- render a session zip to HTML.
  * ``visus doctor``                   -- delegate to ``visus-doctor``.

The entry point is registered as the ``visus`` console script in
``pyproject.toml``; ``visus-doctor`` remains as a shortcut.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

_TASKS_PY = '''"""Generated by `visus new` -- edit this list to drive your bot."""

from visus.desktop import VisusBot

bot = VisusBot()

tasks = [
    {"type": "type_text", "text": "Hello from visus-desktop"},
]

if __name__ == "__main__":
    results = bot.execute_tasks(tasks)
    for r in results:
        print(f"{r.task_index + 1}. {r.task_name} -> {r.success}")
'''

_README_MD = """# {name}

Generated by `visus new`. Edit `tasks.py` to define your automation
and run it with:

```bash
visus run tasks.py
```

See the visus-desktop cookbook at
https://github.com/matheuszwilk/visus-desktop for worked examples.
"""

_GITIGNORE = """\
visus-artifacts/
__pycache__/
.venv/
*.pyc
.DS_Store
"""


def _cmd_new(args) -> int:
    target = Path(args.path)
    if target.exists() and not args.force:
        print(
            f"error: {target} already exists. Re-run with --force to overwrite.",
            file=sys.stderr,
        )
        return 1
    target.mkdir(parents=True, exist_ok=True)
    (target / "tasks.py").write_text(_TASKS_PY, encoding="utf-8")
    (target / "README.md").write_text(
        _README_MD.format(name=target.name), encoding="utf-8"
    )
    (target / ".gitignore").write_text(_GITIGNORE, encoding="utf-8")
    print(f"Scaffolded a new visus-desktop project at {target}.")
    return 0


def _cmd_run(args) -> int:
    script = args.script
    return subprocess.call([sys.executable, script])


def _cmd_report(args) -> int:
    from .core.session import Session

    Session.write_report(args.zip, args.html)
    print(f"Wrote {args.html}")
    return 0


def _cmd_doctor(_args) -> int:
    from . import doctor

    return doctor.main()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="visus",
        description="Visus Desktop CLI -- scaffold, run, report, diagnose.",
    )
    sub = parser.add_subparsers(dest="cmd", required=False)

    p_new = sub.add_parser("new", help="Scaffold a new bot project.")
    p_new.add_argument("path")
    p_new.add_argument("--force", action="store_true")
    p_new.set_defaults(func=_cmd_new)

    p_run = sub.add_parser("run", help="Run a Python script via the active interpreter.")
    p_run.add_argument("script")
    p_run.set_defaults(func=_cmd_run)

    p_report = sub.add_parser("report", help="Render a session zip to HTML.")
    p_report.add_argument("zip")
    p_report.add_argument("--html", required=True)
    p_report.set_defaults(func=_cmd_report)

    p_doctor = sub.add_parser("doctor", help="Run health checks.")
    p_doctor.set_defaults(func=_cmd_doctor)

    args = parser.parse_args(argv)
    if not getattr(args, "cmd", None):
        parser.print_help()
        return 2
    return int(args.func(args))


if __name__ == "__main__":  # pragma: no cover - exercised via console-script
    sys.exit(main(sys.argv[1:]))
